// Checks every icon name the app uses resolves to a Lucide or custom
// icon — a typo would otherwise render the "not drawn yet" placeholder.
//   npm run check:icons          check only
//   npm run check:icons -- --fix also rewrite src/icons/lucide.js to
//                                import exactly the Lucide icons in use
import fs from 'node:fs'
import path from 'node:path'
import * as lucide from 'lucide-react'
import { FOCUS_AREAS, EQUIPMENT } from '../src/data/drills.js'
import { INJURIES, INJURY_CATEGORIES } from '../src/data/injuries.js'

const SRC = path.resolve('src')
const fix = process.argv.includes('--fix')
const pascal = (name) => name.split('-').map((s) => s[0].toUpperCase() + s.slice(1)).join('')

const customFile = fs.readFileSync(path.join(SRC, 'icons/custom/index.jsx'), 'utf8')
const custom = new Set([...customFile.matchAll(/^ {2}'?([a-z0-9-]+)'?: makeIcon\(/gm)].map((m) => m[1]))

// name -> where it's used
const used = new Map()
const use = (name, where) => used.set(name, [...(used.get(name) || []), where])

for (const [label, list] of [['FOCUS_AREAS', FOCUS_AREAS], ['EQUIPMENT', EQUIPMENT], ['INJURY_CATEGORIES', INJURY_CATEGORIES], ['INJURIES', INJURIES]]) {
  for (const item of list) item.icon ? use(item.icon, `${label}.${item.id}`) : console.error(`✗ ${label}.${item.id} has no icon`)
}

// In components: <Icon name="x">, name={a ? 'x' : 'y'}, icon="x" props and icon: 'x' fields.
const files = []
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).forEach((e) => {
  const p = path.join(dir, e.name)
  if (e.isDirectory()) walk(p)
  else if (/\.jsx?$/.test(e.name) && !p.includes(`${path.sep}icons${path.sep}`) && !p.includes(`${path.sep}data${path.sep}`)) files.push(p)
})
walk(SRC)
for (const file of files) {
  const rel = path.relative(SRC, file)
  const text = fs.readFileSync(file, 'utf8')
  for (const m of text.matchAll(/\b(?:name|icon)=\{?["']([a-z0-9-]+)["']/g)) use(m[1], rel)
  for (const m of text.matchAll(/\bname=\{[^}]*\}/g)) for (const s of m[0].matchAll(/'([a-z0-9-]+)'/g)) use(s[1], rel)
  for (const m of text.matchAll(/\bicon: '([a-z0-9-]+)'/g)) use(m[1], rel)
}

let bad = 0
const lucideUsed = []
for (const [name, where] of [...used].sort()) {
  if (custom.has(name)) continue
  if (lucide[pascal(name)]) { lucideUsed.push(name); continue }
  bad++
  console.error(`✗ "${name}" is not a Lucide or custom icon (${[...new Set(where)].join(', ')})`)
}

const registryFile = path.join(SRC, 'icons/lucide.js')
const registry = [...fs.readFileSync(registryFile, 'utf8').matchAll(/^ {2}'?([a-z0-9-]+)'?: [A-Z]/gm)].map((m) => m[1])
const missing = lucideUsed.filter((n) => !registry.includes(n))
const unused = registry.filter((n) => !lucideUsed.includes(n))

if (fix) {
  const key = (n) => (/^[a-z]+$/.test(n) ? n : `'${n}'`)
  fs.writeFileSync(registryFile, [
    '// Lucide icons used by the app, keyed by their lucide.dev name.',
    '// Generated by `npm run check:icons -- --fix`; named imports keep the',
    '// bundle to just these icons.',
    'import {',
    ...lucideUsed.map((n) => `  ${pascal(n)},`),
    "} from 'lucide-react'",
    '',
    'export const LUCIDE = {',
    ...lucideUsed.map((n) => `  ${key(n)}: ${pascal(n)},`),
    '}',
    '',
  ].join('\n'))
  console.log(`Wrote ${lucideUsed.length} Lucide icons to src/icons/lucide.js`)
} else {
  for (const n of missing) { bad++; console.error(`✗ "${n}" is used but not imported in src/icons/lucide.js (run with --fix)`) }
  for (const n of unused) console.warn(`• "${n}" is imported in src/icons/lucide.js but unused (run with --fix)`)
}

const customUsed = [...used.keys()].filter((n) => custom.has(n)).length
console.log(`${used.size} icon names checked: ${lucideUsed.length} Lucide, ${customUsed} custom${bad ? `, ${bad} problem(s)` : ''}`)
process.exit(bad ? 1 : 0)
